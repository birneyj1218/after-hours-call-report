const workflow = {
  name: 'After-hours call report',
  nodes,
  connections,
  active: false,
  settings: {
    executionOrder: 'v1',
    timezone: 'America/Chicago',
    // Call transcripts are personal data: do not keep successful executions.
    saveDataSuccessExecution: 'none',
    saveDataErrorExecution: 'all',
    saveManualExecutions: false,
  },
  pinData: {},
  meta: { templateCredsSetupCompleted: false },
  tags: [],
};

const text = JSON.stringify(workflow, null, 2) + '\n';

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('n8n/after-hours-call-report.json is out of date: run `npm run build:workflow`');
      process.exit(1);
    }
    console.log('n8n/after-hours-call-report.json is up to date');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${nodes.length} nodes)`);
  }
}

module.exports = { workflow, text, bundle };
